// Builds questions-en.js from src/en/gN.txt (one line per question: index ¦ q ¦ 4 options ¦ explanation)
// and src/en/topics.json. Same order as QUESTIONS; first option is still the correct one.
// Checks: every question translated, 4 options, explanation present iff the Russian has one, same numbers.
// src/en/ru-lock.json pins the Russian text each translation was made from, so a rebuilt Russian bank
// can't silently pair a question with the wrong translation (run with --relock after re-translating).
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
eval(fs.readFileSync(path.join(ROOT, 'questions.js'), 'utf8') + ';global.Q=QUESTIONS');
const topics = JSON.parse(fs.readFileSync(path.join(__dirname, 'en/topics.json'), 'utf8'));
const lockFile = path.join(__dirname, 'en/ru-lock.json');
const lock = fs.existsSync(lockFile) ? JSON.parse(fs.readFileSync(lockFile, 'utf8')) : {};
const relock = process.argv.includes('--relock');
const h = (q) => crypto.createHash('sha1').update(q.q + '|' + q.opts.join('|')).digest('hex').slice(0, 10);
const nums = (s) => (String(s).replace(/(\d)[ , ](?=\d{3}\b)/g, '$1').match(/\d+(?:[.,]\d+)?/g) || []).map((n) => n.replace(',', '.')).sort().join(' ');
const en = new Array(Q.length).fill(null), problems = [];
for (let g = 1; g <= 11; g++) {
  const f = path.join(__dirname, 'en/g' + g + '.txt');
  if (!fs.existsSync(f)) continue;
  fs.readFileSync(f, 'utf8').split('\n').forEach((line, ln) => {
    if (!line.trim()) return;
    const p = line.split('¦').map((s) => s.trim()); while (p.length < 7) p.push('');
    const i = +p[0], ru = Q[i];
    if (!ru || ru.g !== g) return problems.push(`g${g}:${ln + 1} bad index ${p[0]}`);
    if (p.length !== 7) return problems.push(`#${i} has ${p.length - 1} fields, expected 6`);
    const [, q, a, b, c, d, x] = p;
    if (!!x !== !!ru.x) problems.push(`#${i} explanation ${x ? 'extra' : 'missing'}`);
    const rn = nums([ru.q, ...ru.opts, ru.x || ''].join(' | ')), enn = nums([q, a, b, c, d, x].join(' | '));
    if (rn !== enn) problems.push(`#${i} numbers differ: ru [${rn}] en [${enn}]`);
    if (lock[i] && lock[i] !== h(ru) && !relock) problems.push(`#${i} Russian text changed since translation — re-translate, then --relock`);
    en[i] = { q, opts: [a, b, c, d], x: x || undefined, topic: topics[ru.topic] };
    if (!topics[ru.topic]) problems.push(`#${i} topic not translated: ${ru.topic}`);
    if (!lock[i] || relock) lock[i] = h(ru);
  });
}
const missing = en.map((e, i) => (e ? null : i)).filter((i) => i !== null);
fs.writeFileSync(lockFile, JSON.stringify(lock));
console.log(`translated ${Q.length - missing.length}/${Q.length}; problems: ${problems.length}`);
problems.slice(0, 40).forEach((p) => console.log('  ' + p));
if (process.argv.includes('--write')) {
  if (problems.length || (missing.length && !process.argv.includes('--partial'))) { console.log('not written: fix the problems / missing first (or --partial for a test build)'); process.exit(1); }
  fs.writeFileSync(path.join(ROOT, 'questions-en.js'), '// English question bank, same order as questions.js. Generated by src/build-en.js.\nconst QUESTIONS_EN = [\n' +
    en.map((e) => (e ? JSON.stringify(e) : 'null')).join(',\n') + '\n];\n');
  console.log('questions-en.js written');
}
